void OLED_DrawChar(int x, int y, char c)
{
    if (c < 0x20 || c > 0x7E) return;          /* 不在字模范围内的字符直接丢 */
    const uint8_t *p = oled_font6x8[c - 0x20];
    for (int col = 0; col < 6; col++) {
        int px = x + col;
        if (px < 0 || px >= OLED_W) continue;
        /* 8 行 → 直接覆盖整页。字模 bit0=顶行，bit7=底行 */
        int page = y >> 3;
        if (page < 0 || page >= OLED_H / 8) continue;
        int idx = page * OLED_W + px;
        oled_buf[idx] = p[col];
    }
}

void OLED_DrawString(int x, int y, const char *s)
{
    while (*s) {
        OLED_DrawChar(x, y, *s++);
        x += 6;                                  /* 每个字 6 像素宽 */
        if (x >= OLED_W) break;                  /* 出界就停 */
    }
}
