/* OLED SSD1306 驱动（I2C 接口）
 * - PB6 = SCL, PB7 = SDA（I2C1 复用 AF4，开漏，外部已加 4.7K 上拉）
 * - 底层 I2C 用寄存器级轮询主发实现（工程里没有 HAL 的 i2c 源文件）
 * - 概念回顾：每帧先发"控制字节" 0x00=命令 / 0x40=数据，随后才是真实内容
 */
#include "main.h"
#include "oled.h"

uint8_t oled_buf[OLED_BUF_SIZE] = {0};

/* ===================== 寄存器级 I2C1 主发（标准模式 100kHz） ===================== */
void OLED_I2C_Init(void)
{
    /* 1) 开时钟：GPIOB + I2C1 */
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOBEN;
    RCC->APB1ENR |= RCC_APB1ENR_I2C1EN;

    /* 2) 复位 I2C1，清掉可能的 BUSY 卡死（F4 I2C 已知坑） */
    RCC->APB1RSTR |= RCC_APB1RSTR_I2C1RST;
    RCC->APB1RSTR &= ~RCC_APB1RSTR_I2C1RST;

    /* 3) PB6/PB7 -> 复用 AF4（I2C1），开漏，无内部上拉（外部已加 4.7K） */
    GPIOB->MODER   &= ~((3u << (6 * 2)) | (3u << (7 * 2)));
    GPIOB->MODER   |=  ((2u << (6 * 2)) | (2u << (7 * 2)));   /* AF */
    GPIOB->OTYPER  |=  (1u << 6) | (1u << 7);                 /* open-drain */
    GPIOB->OSPEEDR |=  ((3u << (6 * 2)) | (3u << (7 * 2)));   /* very high */
    GPIOB->PUPDR   &= ~((3u << (6 * 2)) | (3u << (7 * 2)));   /* no pull */
    GPIOB->AFR[0]  &= ~((0xFu << (6 * 4)) | (0xFu << (7 * 4)));
    GPIOB->AFR[0]  |=  ((4u << (6 * 4)) | (4u << (7 * 4)));   /* AF4 = I2C1 */

    /* 4) I2C 配置：标准模式 100kHz（PCLK1 = 42MHz） */
    I2C1->CR1 &= ~I2C_CR1_PE;        /* 关外设才能写配置 */
    I2C1->CR2  = 42;                /* FREQ[5:0] = APB1 时钟(MHz) = 42 */
    I2C1->TRISE = 43;               /* 1000ns / (1/42MHz) + 1 = 43 */
    I2C1->CCR  = 210;               /* 标准模式: CCR = 42MHz/(2*100kHz) = 210 */
    I2C1->CR1 |= I2C_CR1_PE;        /* 使能外设 */
}

/* 轮询式主发：START -> ADDR(写) -> 数据... -> STOP
 * 返回 0 成功，<0 表示等待超时（如从机不应答，多半是地址/接线问题） */
int OLED_I2C_Write(uint8_t addr, const uint8_t *buf, uint16_t len)
{
    uint32_t to;

    to = 1000000;                                   /* 等总线空闲 */
    while (I2C1->SR2 & I2C_SR2_BUSY) { if (--to == 0) return -1; }

    I2C1->CR1 |= I2C_CR1_START;                     /* 产生 START */
    to = 1000000;
    while (!(I2C1->SR1 & I2C_SR1_SB))  { if (--to == 0) return -1; }

    I2C1->DR = (uint8_t)((addr << 1) & 0xFE);       /* 从机地址(写) */
    to = 1000000;
    while (!(I2C1->SR1 & I2C_SR1_ADDR)) { if (--to == 0) return -1; }
    (void)I2C1->SR2;                                /* 读 SR2 清除 ADDR 标志 */

    for (uint16_t i = 0; i < len; i++) {            /* 逐字节发数据 */
        to = 1000000;
        while (!(I2C1->SR1 & I2C_SR1_TXE)) { if (--to == 0) return -1; }
        I2C1->DR = buf[i];
    }

    to = 1000000;                                   /* 等发送完成(TxE+BTF)再 STOP */
    while (!(I2C1->SR1 & I2C_SR1_TXE)) { if (--to == 0) return -1; }
    to = 1000000;
    while (!(I2C1->SR1 & I2C_SR1_BTF)) { if (--to == 0) return -1; }
    I2C1->CR1 |= I2C_CR1_STOP;
    return 0;
}

/* ===================== OLED（SSD1306）驱动 ===================== */
static uint8_t txbuf[OLED_BUF_SIZE + 1];   /* 控制字节 + 数据，一次事务发出 */

/* ctrl: 0x00 = 命令；0x40 = 显示数据 */
static int oled_write(uint8_t ctrl, const uint8_t *data, uint16_t len)
{
    txbuf[0] = ctrl;
    for (uint16_t i = 0; i < len; i++) txbuf[1 + i] = data[i];
    return OLED_I2C_Write(OLED_I2C_ADDR, txbuf, len + 1);
}

static void oled_cmd(uint8_t c) { oled_write(0x00, &c, 1); }

void OLED_Init(void)
{
    HAL_Delay(100);   /* 等 OLED 上电稳定 */

    /* SSD1306 标准初始化序列（128x64） */
    const uint8_t init[] = {
        0xAE,             /* 关闭显示 */
        0xD5, 0x80,       /* 设置显示时钟分频 */
        0xA8, 0x3F,       /* 复用率 = 63（64 行） */
        0xD3, 0x00,       /* 显示偏移 = 0 */
        0x40,             /* 起始行 = 0 */
        0x8D, 0x14,       /* 电荷泵开启（SSD1306 必须开，否则不亮） */
        0x20, 0x00,       /* 寻址模式：水平（写显存最顺手） */
        0xA1,             /* 段重映射（左右方向） */
        0xC8,             /* COM 扫描方向重映射（上下方向） */
        0xDA, 0x12,       /* COM 引脚硬件配置（128x64 用 0x12） */
        0x81, 0xCF,       /* 对比度 */
        0xD9, 0xF1,       /* 预充电周期 */
        0xDB, 0x40,       /* VCOMH 电平 */
        0xA4,             /* 正常显示（不全屏点亮） */
        0xA6,             /* 不反色 */
        0xAF              /* 开启显示 */
    };
    oled_write(0x00, init, sizeof(init));

    OLED_Clear();
    OLED_Refresh();
}

void OLED_Clear(void)
{
    for (int i = 0; i < OLED_BUF_SIZE; i++) oled_buf[i] = 0;
}

void OLED_Fill(int on)
{
    for (int i = 0; i < OLED_BUF_SIZE; i++) oled_buf[i] = on ? 0xFF : 0x00;
}

void OLED_DrawPixel(int x, int y, int on)
{
    if (x < 0 || x >= OLED_W || y < 0 || y >= OLED_H) return;
    int idx = (y >> 3) * OLED_W + x;         /* 第几页 × 128 + 第几列 */
    if (on) oled_buf[idx] |=  (1u << (y & 7));
    else    oled_buf[idx] &= ~(1u << (y & 7));
}

/* 经典 Bresenham 画线 */
void OLED_DrawLine(int x0, int y0, int x1, int y1, int on)
{
    int dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    int sx = (x0 < x1) ? 1 : -1;
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx - dy, e2;
    for (;;) {
        OLED_DrawPixel(x0, y0, on);
        if (x0 == x1 && y0 == y1) break;
        e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 <  dx) { err += dx; y0 += sy; }
    }
}

void OLED_Refresh(void)
{
    /* 设置列地址 0..127、页地址 0..7（水平寻址模式会自动跨页递增） */
    oled_cmd(0x21); oled_cmd(0x00); oled_cmd(0x7F);
    oled_cmd(0x22); oled_cmd(0x00); oled_cmd(0x07);
    /* 一次事务把 1024 字节显存整屏推上去（控制字节 0x40 = 数据） */
    oled_write(0x40, oled_buf, OLED_BUF_SIZE);
}

